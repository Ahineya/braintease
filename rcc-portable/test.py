#!/usr/bin/env python3
"""Execute direct C16/RCC IR lowering through the native and Ripple backends."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ENV = dict(os.environ, RCC_NATIVE_HEADLESS='1', RCC_NATIVE_NET='off', RIPPLE_NET='off')


def run(command, expected=0, timeout=40):
    result = subprocess.run(list(map(str, command)), capture_output=True, text=True,
                            env=ENV, timeout=timeout)
    assert result.returncode == expected, (command, result.returncode, result.stdout, result.stderr)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-only', action='store_true')
    parser.add_argument('--portable-backend',action='store_true',help='use the portable backend for Ripple code generated by the portable frontend')
    parser.add_argument('--rcc', type=Path, default=ROOT / 'target/release/rcc')
    args = parser.parse_args()
    run([sys.executable, HERE / 'build.py'])
    compiler = [sys.executable, HERE / 'cc.py', '--rcc', args.rcc]
    if args.portable_backend:
        from build_ripple import ensure_host
        backend=ensure_host()
    with tempfile.TemporaryDirectory(prefix='rcc-c-tests-') as temporary:
        directory = Path(temporary)

        def execute(source, target, name, expected=0):
            output = directory / (name + '.' + target)
            if target == 'native':
                if source.suffix == '.ir':
                    run([args.rcc, 'link-native', source, '-o', output])
                else:
                    run([*compiler, source, '--target', 'native', '-o', output])
                return run([output], expected=expected)
            assembler = ROOT / 'src/ripple-asm/target/release'
            assembly, obj = output.with_suffix('.asm'), output.with_suffix('.pobj')
            if source.suffix == '.ir':
                if args.portable_backend:
                    run([backend,source,'-o',assembly])
                else:
                    run([args.rcc, 'generate-asm', '-i', source, '-o', assembly])
            else:
                run([*compiler, source, '-o', assembly,*(['--backend','portable'] if args.portable_backend else [])])
            run([assembler / 'rasm', 'assemble', assembly, '-o', obj,
                 '--bank-size', '64000', '--max-immediate', '65535','--memory-offset','0'])
            run([assembler / 'rlink', ROOT / 'runtime/crt0.pobj', ROOT / 'runtime/libruntime.par',
                 obj, '-f', 'binary', '--bank-size', '64000', '-o', output])
            return run([ROOT / 'target/release/rvm', output, '--headless', '--net', 'off',
                        '--disk', directory / (name + '.disk'), '--exit-code',
                        '--max-instructions', '10000000', '--timeout', '20'], expected=expected)

        fixtures = [(HERE / f'tests/{name}.c', None) for name in
                    ['scalars', 'control', 'memory', 'strings', 'aggregates', 'varargs', 'relocations', 'inline_switch', 'wide_unary', 'floating_unary', 'preprocessor']]
        fixtures.append((HERE / 'tests/bitfields.c', None))
        for name in ['test_nested_struct_return', 'test_large_struct_byval',
                     'test_union_return', 'test_nested_field_assign_from_call']:
            path = ROOT / f'c-test/tests/memory/structs/{name}.c'
            fixtures.append((path, json.loads(path.with_suffix('.meta.json').read_text())['expected']))
        for category, name in [
                ('core/functions', 'test_varargs_sum'),
                ('runtime', 'test_va_arg_double'),
                ('runtime', 'test_va_arg_ptr'),
                ('runtime', 'test_va_arg_register_pressure'),
                ('memory/pointers', 'test_static_address_initializers')]:
            path = ROOT / f'c-test/tests/{category}/{name}.c'
            fixtures.append((path, json.loads(path.with_suffix('.meta.json').read_text())['expected']))
        targets = ['native'] if args.native_only else ['native', 'ripple']
        def check(item):
            source, expected, target = item
            name = source.stem
            result = execute(source, target, name)
            if name == 'strings':
                assert 'portable C11 frontend' in result.stdout
            if expected is not None:
                assert expected in result.stdout, (source, target, result.stdout)
            return f'{name}: {target} passed'
        with ThreadPoolExecutor(max_workers=2) as pool:
            for message in pool.map(check, [(path, expected, target) for path, expected in fixtures for target in targets]):
                print(message, flush=True)

        # Valid SSA can place a dominating definition after its use in the
        # block vector. Physical register allocation must not follow that order.
        original = HERE / 'tests/backward_values.ir'
        for target in targets:
            source = directory / f'backward-{target}.ir'
            source.write_text(original.read_text().replace('module backward_values {',
                              'module backward_values {\n  target ' + target))
            execute(source, target, 'backward-values', expected=28)
            print(f'backward block definitions: {target} passed', flush=True)

        # Validate that both execution paths propagate failures from main.
        failure = directory / 'failure.c'
        failure.write_text('int main(void) {return 17;}\n')
        for target in targets:
            execute(failure, target, 'failure', expected=17)

        # Separately compiled units must keep local symbols private and use the
        # same scalar/pointer ABI as the existing RCC frontend.
        sources = [
            'static int bias=9; long compute(int n){return n+bias;}\n',
            'long compute(int);int main(void){return compute(8)==17?0:1;}\n',
        ]
        units = []
        for i, source in enumerate(sources):
            path = directory / f'unit{i}.c'
            path.write_text(source)
            ir = path.with_suffix('.ir')
            if i == 0:
                run([*compiler, path, '--target', 'native', '--emit-ir', '-o', ir])
            else:
                result = run([args.rcc, 'compile', path, '--target', 'native', '--emit-ir'])
                ir.write_text(result.stdout)
            units.append(ir)
        linked = directory / 'mixed-frontends'
        run([args.rcc, 'link-native', *units, '-o', linked])
        run([linked])

        # Aggregate signatures and ownership must agree in both directions,
        # including nested objects, pointers, callbacks and wide constants.
        header = '''
struct Pair {int tag; long value;};
struct Payload {struct Pair pair; double weight; int *pointer; int data[3];};
struct Payload transform(struct Payload,long,int*);
'''
        provider = header + '''
struct Payload transform(struct Payload p,long delta,int *marker) {
    p.pair.tag++;p.pair.value+=delta;p.weight+=0.5;
    p.data[2]++;*marker=7;return p;
}
'''
        consumer = header + '''
int main(void) {
    int local=9,marker=0;
    struct Payload input={.pair={2,70000L},.weight=2.25,.pointer=&local,.data={1,2,3}};
    struct Payload (*callback)(struct Payload,long,int*)=transform;
    struct Payload result=callback(input,0L,&marker);
    if(marker!=7 || result.pair.tag!=3 || result.pair.value!=70000L)return 1;
    if(result.weight!=2.75 || *result.pointer!=9 || result.data[2]!=4)return 2;
    if(input.pair.tag!=2 || input.weight!=2.25 || input.data[2]!=3)return 3;
    result=transform(result,1L,&marker);
    return result.pair.value==70001L && result.data[2]==5?0:4;
}
'''
        def mixed(label, sources, target, portable_provider):
            name = f'mixed-{label}-{target}-{int(portable_provider)}'
            units = []
            for i, source in enumerate(sources):
                path = directory / f'{name}-{i}.c'
                path.write_text(source)
                ir = path.with_suffix('.ir')
                if (i == 0) == portable_provider:
                    run([*compiler, path, '--target', target, '--emit-ir', '-o', ir])
                else:
                    result = run([args.rcc, 'compile', path,
                                  '--target', target, '--emit-ir', '-I', ROOT / 'runtime/include'])
                    ir.write_text(result.stdout)
                units.append(ir)
            output = directory / name
            if target == 'native':
                run([args.rcc, 'link-native', *units, '-o', output])
                run([output])
            else:
                assembler = ROOT / 'src/ripple-asm/target/release'
                objects = []
                for i,ir in enumerate(units):
                    assembly, obj = ir.with_suffix('.asm'), ir.with_suffix('.pobj')
                    if args.portable_backend and ((i==0)==portable_provider):
                        run([backend,ir,'-o',assembly])
                    else:
                        run([args.rcc, 'generate-asm', '-i', ir, '-o', assembly])
                    run([assembler / 'rasm', 'assemble', assembly, '-o', obj,
                         '--bank-size', '64000', '--max-immediate', '65535','--memory-offset','0'])
                    objects.append(obj)
                run([assembler / 'rlink', ROOT / 'runtime/crt0.pobj', ROOT / 'runtime/libruntime.par',
                     *objects, '-f', 'binary', '--bank-size', '64000', '-o', output])
                run([ROOT / 'target/release/rvm', output, '--headless', '--net', 'off',
                     '--disk', directory / f'{name}.disk', '--exit-code',
                     '--max-instructions', '10000000', '--timeout', '20'])
            print(f'{name}: passed', flush=True)

        groups = {'aggregates': [provider, consumer]}
        header = '#include <stdarg.h>\nlong collect(int,long,...);\n'
        groups['varargs'] = [header + '''
long collect(int tag,long seed,...) {
    va_list ap,copy;va_start(ap,seed);va_copy(copy,ap);
    if(tag!=7 || va_arg(ap,unsigned long long)!=0x123456789abcdef0ULL)return -1L;
    if(va_arg(copy,unsigned long long)!=0x123456789abcdef0ULL)return -2L;
    if(va_arg(ap,double)!=1.5)return -3L;
    if(*va_arg(ap,int*)!=19)return -4L;
    if(va_arg(ap,char*)[0]!='o')return -5L;
    va_end(ap);va_end(copy);return seed+1L;
}
''', header + '''
int main(void) {
    int number=19;long (*callback)(int,long,...)=collect;
    long result=callback(7,0L,0x123456789abcdef0ULL,1.5f,&number,"ok");
    return result==1L?0:1;
}
''']
        header = '''
struct Entry {char *name; long *pointer; int (*callback)(int); double weight;};
extern long number;
extern struct Entry entries[2];
'''
        groups['relocations'] = [header + '''
long number=70000L;
static int twice(int n){return n*2;}
struct Entry entries[2]={{"first",&number,twice,2.25},{"second",&number,twice,1.5}};
''', header + '''
int main(void) {
    if(entries[0].name[0]!='f' || *entries[1].pointer!=70000L)return 1;
    if(entries[0].callback(9)!=18 || entries[0].weight!=2.25 || entries[1].weight!=1.5)return 2;
    *entries[1].pointer=11L;return number==11L?0:3;
}
''']
        for label, sources in groups.items():
            for target in targets:
                for portable_provider in [True, False]:
                    mixed(label, sources, target, portable_provider)

        # Pending capabilities must report a diagnostic and preserve outputs.
        rejected = {
            'vla': ('int main(void){int n=3;int a[n];return a[0];}', 'variable length'),
            'va_start': ('void f(void){void *ap;__builtin_va_start(ap,ap);}', 'va_start requires'),
            'atomic': ('_Atomic int a;', 'not yet supported'),
            'alignment': ('int main(void){_Alignas(2) int a=0;return a;}', 'extended alignment'),
            'encoding': ('int main(void){return sizeof(u"abc");}', 'prefixed string'),
            'character_encoding': ("int main(void){return u'a';}", 'prefixed character'),
            'tls': ('_Thread_local int a;', 'thread storage'),
            'longdouble': ('long double f(long double a){return a;}', 'long double'),
            'assertion': ('_Static_assert(sizeof(int)==4,"wrong layout");', 'static assertion failed'),
            'nonconstant': ('int x;int value=x;', 'initializer must be constant'),
            'narrow_address': ('int x;int value=(int)&x;', 'requires two cells'),
            'automatic_address': ('void f(void){int x;static int *p=&x;}', 'static object address'),
        }
        for name, (source, diagnostic) in rejected.items():
            path = directory / f'{name}.c'
            path.write_text(source)
            output = directory / 'preserved.ir'
            output.write_text('keep-existing-output')
            result = run([*compiler, path, '--emit-ir', '-o', output], expected=1)
            assert diagnostic in result.stderr, result.stderr
            assert output.read_text() == 'keep-existing-output'

        ir = run([*compiler, HERE / 'tests/memory.c', '--target', 'native', '--emit-ir']).stdout
        assert 'load volatile i16' in ir and 'store volatile i16' in ir
        assert 'ptrtolinear i32' in ir and 'getelementptr i16*' in ir
        ir = run([*compiler, HERE / 'tests/aggregates.c', '--target', 'native', '--emit-ir']).stdout
        for name in ['get_observed', 'get_marked']:
            body = ir.split(f'@"{name}"() {{', 1)[1].split('\n  }', 1)[0]
            assert 'load volatile i16' in body, body
        print(f'mixed frontends, nonzero exits, volatile/bank-aware IR and {len(rejected)} rejection checks passed')


if __name__ == '__main__':
    main()
