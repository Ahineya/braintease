#!/usr/bin/env python3
"""Compile the NetSurf dependencies for both C16 targets."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from adapt import prepare, write_changed

PORT = Path(__file__).resolve().parent
ROOT = PORT.parents[1]
LIBRARIES = ('libwapcaplet', 'libparserutils', 'libhubbub', 'libcss', 'libdom')


def includes(source):
    return [PORT / 'config', *[source / lib / 'include' for lib in LIBRARIES],
            source / 'libdom/bindings',
            ROOT / 'ports/fuzix/ripple/include', ROOT / 'ports/fuzix/upstream/Library/include',
            ROOT / 'runtime/include', ROOT / 'ports/fuzix/ripple']


def sources(source):
    tasks = []
    for library in LIBRARIES:
        for path in sorted((source / library / 'src').rglob('*.c')):
            if path.name in ('codec_utf16.c', 'utf16.c', 'autogenerated-element-type.c', 'css_property_parser_gen.c'):
                continue
            tasks.append((library, path))
        if library == 'libdom':
            tasks.append((library, source / library / 'bindings/hubbub/parser.c'))
    return tasks


def build(output, compiler, target, jobs=3):
    output, compiler = Path(output).resolve(), Path(compiler).resolve()
    source = prepare(output / 'source')
    directories = includes(source)
    flags = ['--target', target, '-DRIPPLE_MMU=1', '-DNO_64BIT', '-DWITHOUT_ICONV_FILTER', '-DNDEBUG']
    for directory in directories:
        flags += ['-I', str(directory)]
    fingerprint = hashlib.sha256(str((compiler, compiler.stat().st_mtime_ns, flags)).encode())
    for directory in [source, *directories]:
        for path in sorted(directory.rglob('*')):
            if path.is_file() and path.suffix in ('.h', '.inc'):
                if directory == source and path.relative_to(source).parts[0] not in LIBRARIES:
                    continue
                fingerprint.update(str(path.relative_to(directory)).encode())
                fingerprint.update(path.read_bytes())
    base = fingerprint.digest()
    tasks = sources(source)
    if target == 'ripple':
        # The RVM backend lowers CSS floating-point conversion helpers to
        # the shared software arithmetic runtime. No float printf or libm
        # profile is needed for this dependency milestone.
        tasks.append(('runtime', ROOT / 'runtime/softfloat.c'))
    objects = output / target
    objects.mkdir(parents=True, exist_ok=True)

    def compile_one(task):
        library, path = task
        relative = path.relative_to(source / library).with_suffix('') if library in LIBRARIES else Path(path.stem)
        # Preserve the existing cache names for the original source trees.
        if relative.parts[0] == 'src':
            relative = Path(*relative.parts[1:])
        ir = objects / (library + '_' + '_'.join(relative.parts) + '.ir')
        stamp = ir.with_suffix('.json')
        key = hashlib.sha256(base + path.read_bytes()).hexdigest()
        try:
            cached = ir.exists() and ir.stat().st_size and json.loads(stamp.read_text())['key'] == key
        except (OSError, ValueError, KeyError):
            cached = False
        if not cached:
            result = subprocess.run([str(compiler), 'compile', str(path), *flags,
                '-I', str(source / library / 'src' if library in LIBRARIES else path.parent), '--emit-ir'], capture_output=True,
                env=dict(os.environ, RUST_LOG='error'))
            ir.with_suffix('.log').write_bytes(result.stderr + (result.stdout if result.returncode else b''))
            if result.returncode:
                return None, f'{library}/{relative}: see {ir.with_suffix(".log")}'
            write_changed(ir, result.stdout)
            stamp.write_text(json.dumps(dict(key=key)) + '\n')
        return ir, None

    with ThreadPoolExecutor(max_workers=jobs) as pool:
        results = list(pool.map(compile_one, tasks))
    failures = [error for _, error in results if error]
    if failures:
        raise RuntimeError('\n'.join(failures))
    paths = [path for path, _ in results]
    write_changed(objects / 'objects.json', (json.dumps(list(map(str, paths)), indent=2) + '\n').encode())
    print(f'Compiled {len(paths)} NetSurf dependency/runtime objects ({target})', flush=True)
    return paths


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', type=Path, default=ROOT / 'build/netsurf')
    parser.add_argument('--compiler', type=Path, default=ROOT / 'target/release/rcc')
    parser.add_argument('--target', choices=('native', 'ripple'), default='native')
    parser.add_argument('-j', '--jobs', type=int, default=3)
    args = parser.parse_args()
    try:
        build(args.build, args.compiler, args.target, args.jobs)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
