#!/usr/bin/env python3
"""Bounded wire-reader tables from the pinned TL types, without host TDLib."""
from pathlib import Path
import re

HERE=Path(__file__).resolve().parent
keys='id access_hash first_name last_name username title peer peer_id user_id chat_id channel_id from_id message date top_message unread_count pts pts_count qts seq seq_start count dialogs messages users chats updates update new_messages other_updates state intermediate_state folder_id order media action max_id read_inbox_max_id dialog still_unread_count folder_peers admin_rights default_banned_rights banned_rights'.split()
constructors=[];rules=[];types=True
for line in (HERE/'upstream/telegram_api.tl').read_text().splitlines():
    if line.startswith('---'):
        types=line=='---types---';continue
    match=re.match(r'^([\w.]+)#([0-9a-f]+)\s*(.*?) = ',line)
    if not types or not match or match[1]=='vector':continue
    flags={};fields=[]
    for field in match[3].split():
        name,kind=field.split(':',1);condition=0
        if '?' in kind:
            flag,kind=kind.split('?');var,bit=flag.split('.')
            condition=flags[var]*32+int(bit)+1
        vector=0
        if kind.startswith(('Vector<','vector<')):
            vector=16 if kind.startswith('Vector') else 32
            kind=kind[kind.index('<')+1:-1]
        if kind=='#':
            flags[name]=len(flags);assert len(flags)<=3
            op=5+flags[name]
        else:op={'true':0,'int':1,'long':2,'double':2,'bytes':3,'string':3,'int128':8,'int256':9}.get(kind,4)+vector
        fields.append((op,condition,keys.index(name)+1 if name in keys else 0))
    constructors.append((int(match[2],16),len(rules),len(fields)))
    rules.extend(fields)
assert len(rules)<65536
(HERE/'tl_schema.c').write_text('/* Generated by generate_tl.py; upstream Boost license retained. */\n#include "tl.h"\n'+
    'const TgRule tg_rules[]={\n'+''.join('{%d,%d,%d},\n'%v for v in rules)+'};\n'+
    'const TgConstructor tg_constructors[]={\n'+''.join('{0x%xUL,%d,%d},\n'%v for v in sorted(constructors))+'};\n'+
    'const unsigned tg_constructor_count=%d;\n'%len(constructors))
(HERE/'tl_fields.h').write_text('/* Generated by generate_tl.py. */\n#ifndef TG_TL_FIELDS_H\n#define TG_TL_FIELDS_H\n'+
    ''.join('#define F_%s %d\n'%(name,i) for i,name in enumerate(keys))+'#define TG_FIELDS %d\n#endif\n'%len(keys))
