#!/usr/bin/env python3
"""Verify original courses and generate octet-safe built-in courses."""
import argparse,hashlib,json,zlib
from pathlib import Path
HERE=Path(__file__).resolve().parent
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
sources=json.loads((HERE/'source.json').read_text())['courses']
lengths=[]
out='/* Generated by assets.py from pinned KDE Kolf courses. GPL-2.0-or-later. */\n'
for i,source in enumerate(sources):
    data=(HERE/source['local']).read_bytes()
    assert hashlib.sha256(data).hexdigest()==source['sha256'],source['local']
    # Locale alternatives do not affect play. Keep original files intact on disk,
    # and embed only the untranslated fallback to save guest startup/memory.
    data=b''.join(line for line in data.splitlines(keepends=True) if not line.startswith((b'Name[',b'Comment[')))
    lengths.append(len(data))
    compressor=zlib.compressobj(level=9,wbits=-15)
    data=compressor.compress(data)+compressor.flush()
    # C16 string escapes use the language's UTF-8 string representation;
    # numeric octet initializers preserve compressed values above 127 exactly.
    out+='static const unsigned char golf_course_%d[] = {\n'%i
    out+=''.join('    '+','.join(str(b) for b in data[at:at+24])+',\n' for at in range(0,len(data),24))+'};\n'
out+='typedef struct BuiltinCourse {const char *name;const unsigned char *text;unsigned long length,packed;} BuiltinCourse;\nstatic const BuiltinCourse builtins[] = {\n'
for i,source in enumerate(sources):
    out+='    {"%s",golf_course_%d,%d,sizeof(golf_course_%d)},\n'%(Path(source['local']).stem,i,lengths[i],i)
out+='};\n#define BUILTIN_COUNT 8\n'
if args.check:assert (HERE/'courses.inc').read_text()==out,'Run ports/kolf/assets.py'
else:(HERE/'courses.inc').write_text(out)
print('Kolf: eight pinned courses and built-in embeddings verified')
