#!/usr/bin/env python3
"""Verify the pinned Lucide sources and compile baked masks into static A8 tables."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / 'fusede/icons/lucide'

def verify():
    upstream = json.loads((SOURCE / 'UPSTREAM.json').read_text())
    masks = json.loads((HERE / 'masks.json').read_text())
    assert masks['revision'] == upstream['revision'] and masks['sizes'] == [16, 32]
    for file in upstream['files']:
        assert Path(file['file']).name == file['file']
        assert hashlib.sha256((SOURCE / file['file']).read_bytes()).hexdigest() == file['sha256']
    expected = {Path(f['file']).stem for f in upstream['files'] if f['file'].endswith('.svg')}
    expected.add('arrow-up')
    assert {i['name'] for i in masks['icons']} == expected
    assert len(masks['icons']) == len(expected)
    for item in masks['icons']:
        assert item['file'] == ('arrow-left.svg' if item['name'] == 'arrow-up' else item['name'] + '.svg')
        assert item['turns'] == (1 if item['name'] == 'arrow-up' else 0)
        for size in masks['sizes']:
            values = item['masks'][str(size)]
            assert len(values) == size * size
            assert all(type(v) is int and 0 <= v <= 255 for v in values)
            assert any(0 < v < 255 for v in values) and max(values) > 128
    return upstream, masks

def generate():
    upstream, masks = verify()
    items = masks['icons']
    lines = ['/* Lucide artwork: ISC and Feather MIT. See LICENSE.Lucide.txt. */',
             '/* Generated by icons/build.py. Application code uses icon names. */',
             '#include "data.h"', '#include <string.h>']
    for size in masks['sizes']:
        pixels = [v for item in items for v in item['masks'][str(size)]]
        lines += [f'static const uint8_t mask_{size}[]={{']
        lines += ['    '+','.join(map(str,pixels[i:i+32]))+',' for i in range(0,len(pixels),32)]
        lines += ['};', f'static const lv_font_fmt_txt_glyph_dsc_t glyphs_{size}[]={{', '    {0},']
        lines += [f'    {{.bitmap_index={i*size*size}UL,.adv_w={size*16},.box_w={size},.box_h={size}}},' for i in range(len(items))]
        lines += ['};', f'static const lv_font_fmt_txt_cmap_t cmap_{size}[]={{',
                  f'{{.range_start=61696UL,.range_length={len(items)},.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}}};',
                  f'static const lv_font_fmt_txt_dsc_t data_{size}={{.glyph_bitmap=mask_{size},.glyph_dsc=glyphs_{size},.cmaps=cmap_{size},.cmap_num=1,.bpp=8,.stride=1}};',
                  f'const lv_font_t ui_icons_{size}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={size},.static_bitmap=1,.dsc=&data_{size}}};']
    lines += ['static const char *names[]={'+','.join(json.dumps(i['name']) for i in items)+'};',
              'static const char texts[][4]={']
    for index in range(len(items)):
        cp = 0xf100 + index
        lines.append('    {' + ','.join(map(str,chr(cp).encode())) + ',0},')
    lines += ['};', f'unsigned ui_icon_count(void) {{return {len(items)};}}',
              'const char *ui_icon_name(unsigned index) {return index<ui_icon_count()?names[index]:NULL;}',
              'const char *ui_icon_text(const char *name) {unsigned i;if(name)for(i=0;i<ui_icon_count();i++)if(!strcmp(name,names[i]))return texts[i];return NULL;}']
    (HERE/'data.c').write_text('\n'.join(lines)+'\n')
    (HERE/'LICENSE.Lucide.txt').write_bytes((SOURCE/'LICENSE').read_bytes())
    (HERE/'source.json').write_text(json.dumps(dict(revision=upstream['revision'],source_manifest='../../fusede/icons/lucide/UPSTREAM.json',
        sizes=masks['sizes'],names=[i['name'] for i in items],representation='Static A8 masks; private glyph transport behind named icon widgets',
        rasterizer=masks['rasterizer'],masks_sha256=hashlib.sha256((HERE/'masks.json').read_bytes()).hexdigest(),
        generated_sha256=hashlib.sha256((HERE/'data.c').read_bytes()).hexdigest()),indent=2)+'\n')

if __name__ == '__main__':
    generate()
