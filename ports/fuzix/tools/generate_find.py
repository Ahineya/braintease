#!/usr/bin/env python3
"""Combine find.y's upstream C and token names with the portable C99 parser."""
from pathlib import Path
import re
import sys
PORT=Path(__file__).resolve().parents[1]
source=PORT/'upstream/Applications/MWC/cmd/find.y'
text=source.read_text()
prologue=text.split('%{',1)[1].split('%}',1)[0]
directives=text.split('%}',1)[1].split('%%',1)[0]
tokens=[]
for line in directives.splitlines():
    if line.startswith(('%left','%token')):
        tokens.extend(re.findall(r'\b[A-Z][A-Z0-9_]*\b',line))
enum='enum find_token {\n'+',\n'.join(f'    {name} = {258+i}' for i,name in enumerate(tokens))+'\n};\n'
body=text.split('%%',2)[2]
parser=(PORT/'ripple/find-parser.inc').read_text()
header='/* Generated by tools/generate_find.py from find.y and ripple/find-parser.inc. */\n'
output=source.parent/'find.c'
rendered=header+prologue+enum+parser+body
if '--check' in sys.argv:
    if not output.exists() or output.read_text()!=rendered:
        raise SystemExit('find.c needs regeneration with tools/generate_find.py')
else:
    output.write_text(rendered)
