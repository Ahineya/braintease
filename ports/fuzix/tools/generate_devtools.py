#!/usr/bin/env python3
"""Regenerate the checked-in expr/AWK parsers and AWK dispatch table (needs bison)."""
from pathlib import Path
import re
import subprocess
import sys
PORT = Path(__file__).resolve().parents[1]
AWK = PORT / 'awk'

def native_stacks(filename):
    text = filename.read_text()
    text = text.replace('yytype_int16 *yyss = yyssa;', 'yytype_int16 *yyss = ripple_absolute_pointer(yyssa);')
    text = text.replace('YYSTYPE *yyvs = yyvsa;', 'YYSTYPE *yyvs = ripple_absolute_pointer(yyvsa);')
    text = text.replace('yyss1 != yyssa', 'yyss1 != (yytype_int16 *)ripple_absolute_pointer(yyssa)')
    text = text.replace('yyss != yyssa', 'yyss != (yytype_int16 *)ripple_absolute_pointer(yyssa)')
    # Bison parsers are already non-reentrant (global yychar/yylval). Keep the
    # dispatch state in memory too: RCC's local state across backward gotos
    # otherwise depends on the debug instrumentation changing register pressure.
    marker = text.index('  int yystate;')
    opening = text.rfind('{', 0, marker)
    beginning = text.index('  YYDPRINTF ((stderr, "Starting parse', marker)
    declarations = text[opening+1:beginning]
    declarations = declarations.replace('yytype_int16 *yyss = ripple_absolute_pointer(yyssa);', 'yytype_int16 *yyss;')
    declarations = declarations.replace('YYSTYPE *yyvs = ripple_absolute_pointer(yyvsa);', 'YYSTYPE *yyvs;')
    resets = '  yyss = ripple_absolute_pointer(yyssa);\n  yyvs = ripple_absolute_pointer(yyvsa);\n  yystacksize = YYINITDEPTH; yylen = 0; yytoken = 0;\n'
    insertion = text.rfind('/*----------.', 0, opening)
    assert insertion >= 0
    text = text[:insertion] + '\n/* Ripple: non-reentrant parser state; see generate_devtools.py. */\n' + declarations + text[insertion:opening+1] + '\n' + resets + text[beginning:]
    filename.write_text(text)

def dispatch():
    tokens = {name: int(value) for name, value in re.findall(r'^\s*([A-Z][A-Z0-9_]*)\s*=\s*(\d+)', (AWK/'awkgram.tab.h').read_text(), re.M)}
    first, last = tokens['FIRSTTOKEN'], tokens['LASTTOKEN']
    names = {value: name for name, value in tokens.items() if first <= value <= last}
    assert len(names) == last - first + 1, 'incomplete AWK token header'
    funcs = dict(re.findall(r'\{\s*([A-Z][A-Z0-9_]*),\s*"([a-z_]+)"', (AWK/'maketab.c').read_text()))
    source = '/* Generated by tools/generate_devtools.py from maketab.c and awkgram.tab.h. */\n#include <stdio.h>\n#include "awk.h"\n#include "awkgram.tab.h"\n\n'
    source += 'static const char *const printname[] = {\n'
    source += ''.join('    "'+names[n]+'",\n' for n in range(first, last+1)) + '};\n\n'
    source += 'Cell *(*proctab[])(Node **, int) = {\n'
    source += ''.join('    '+funcs.get(names[n], 'nullproc')+', /* '+names[n]+' */\n' for n in range(first, last+1)) + '};\n\n'
    source += '''const char *tokname(int n) {
    static char buf[100];
    if (n < FIRSTTOKEN || n > LASTTOKEN) {
        snprintf(buf, sizeof(buf), "token %d", n);
        return buf;
    }
    return printname[n-FIRSTTOKEN];
}
'''
    return source

if '--check' not in sys.argv:
    subprocess.run(['bison','--no-lines','-o','upstream/Applications/MWC/cmd/expr.c','upstream/Applications/MWC/cmd/expr.y'],cwd=PORT,check=True)
    subprocess.run(['bison','--no-lines','-d','-o','awkgram.tab.c','awkgram.y'],cwd=AWK,check=True)
    native_stacks(PORT/'upstream/Applications/MWC/cmd/expr.c')
    native_stacks(AWK/'awkgram.tab.c')
    (AWK/'proctab.c').write_text(dispatch())
else:
    assert (AWK/'proctab.c').read_text() == dispatch(), 'AWK dispatch table needs regeneration'
