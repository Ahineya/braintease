"""Extract pinned GNOME puzzles and optionally regenerate their raster artwork.

Normal builds consume checked-in generated assets and need no SVG libraries.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    p.add_argument('--raster', action='store_true')
    args = p.parse_args()
    source = json.loads((HERE / 'source.json').read_text())
    for name, sha in source['files'].items():
        if hashlib.sha256((HERE / 'upstream' / name).read_bytes()).hexdigest() != sha:
            raise ValueError('changed upstream file: ' + name)
    text = (HERE / 'upstream/src/klotski-window.vala').read_text()
    levels = []
    pattern = r'\{\s*N_\("([^"]+)"\), /\* group \*/ (\d+),\s*/\* width and height \*/ (\d+), (\d+),\s*((?:"[^"\n]*"\s*\+?\s*)+)\}'
    for name, group, w, h, data in re.findall(pattern, text):
        rows = re.findall(r'"([^"\n]*)"', data)
        w, h = int(w), int(h)
        if len(rows) != h or any(len(row) != w for row in rows):
            raise ValueError('invalid puzzle: ' + name)
        levels.append(dict(name=name, group=int(group), width=w, height=h, rows=rows))
    if len(levels) != 28:
        raise ValueError('expected all 28 original puzzles')
    header = ['/* Generated from GNOME Klotski 3.38.2; GPL-3.0-or-later. */',
              'const KLevel k_levels[K_LEVELS] = {']
    for level in levels:
        header += ['    {' + json.dumps(level['name']) + ', ' +
                   ', '.join(str(level[k]) for k in ('group', 'width', 'height')) + ',']
        header += ['     ' + json.dumps(row) for row in level['rows']]
        header[-1] += '},'
    header += ['};', '']
    generated = '\n'.join(header)
    target = HERE / 'levels.inc'
    if args.check:
        if target.read_text() != generated:
            raise ValueError('stale levels.inc; run assets.py')
    else:
        target.write_text(generated)
    if args.raster:
        from raster import bake
        # Original tile is 34 px, with a half-tile margin above/below. Bake
        # only the central 34px strip used by upstream's draw_square().
        svg = HERE / 'upstream/data/assets.svg'
        image = bake(svg)
        import struct, zlib
        def chunk(name,data):
            return struct.pack('>I',len(data))+name+data+struct.pack('>I',zlib.crc32(name+data))
        scan=b''.join(b'\0'+bytes(v for p in image[y*918:(y+1)*918] for v in p) for y in range(34))
        (HERE/'tiles.png').write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',918,34,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(scan,9))+chunk(b'IEND',b''))
        # A 9x3 grid fits the existing image protocol's 512px width limit.
        grid = [image[(row%34)*918+(row//34*9+col//34)*34+col%34] for row in range(102) for col in range(306)]
        words = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in grid]
        out = ['/* GNOME assets.svg raster, GPL-3.0-or-later; generated by assets.py --raster. */',
               'static const unsigned short k_tiles[31212] = {']
        out += ['    ' + ','.join(str(x) for x in words[i:i+18]) + ',' for i in range(0, len(words), 18)]
        out += ['};', '']
        (HERE / 'tiles.inc').write_text('\n'.join(out))
        (HERE / 'tiles.sha256').write_text(hashlib.sha256((HERE / 'tiles.inc').read_bytes()).hexdigest() + '\n')
    if hashlib.sha256((HERE / 'tiles.inc').read_bytes()).hexdigest() != (HERE / 'tiles.sha256').read_text().strip():
        raise ValueError('changed tile raster; regenerate explicitly with --raster')
    print('Klotski: pinned sources, 28 puzzles, and tile raster verified')


if __name__ == '__main__':
    main()
