#!/usr/bin/env python3
"""Original deterministic Shikaku puzzles, verified by an exact-cover solver."""
import argparse, json, random
from pathlib import Path
SIZES=(5,7,10,15,20,25)
COUNT=12
ROOT=Path(__file__).resolve().parent

def candidates(n,clues):
    occupied=sum(1<<p for p in clues)
    result=[]
    for p,area in sorted(clues.items()):
        x,y=p%n,p//n
        for w in range(1,n+1):
            if area%w:continue
            h=area//w
            if h>n:continue
            for yy in range(max(0,y-h+1),min(y,n-h)+1):
                for xx in range(max(0,x-w+1),min(x,n-w)+1):
                    mask=sum(((1<<w)-1)<<(r*n+xx) for r in range(yy,yy+h))
                    if mask&occupied==1<<p:result.append((mask,(xx,yy,w,h,p)))
    return result

def solutions(n,clues,limit=2,budget=100000):
    cs=candidates(n,clues);bycell=[[] for _ in range(n*n)]
    for i,(mask,_) in enumerate(cs):
        bits=mask
        while bits:
            bit=bits&-bits;bycell[bit.bit_length()-1].append(i);bits-=bit
    allcells=(1<<(n*n))-1;answers=[];nodes=0
    def visit(covered,chosen):
        nonlocal nodes
        nodes+=1
        if nodes>budget:raise TimeoutError('exact-cover budget exceeded')
        if covered==allcells:answers.append([cs[i][1] for i in chosen]);return
        best=None;remaining=allcells^covered
        while remaining:
            bit=remaining&-remaining;remaining-=bit
            choices=[i for i in bycell[bit.bit_length()-1] if not cs[i][0]&covered]
            if not choices:return
            if best is None or len(choices)<len(best):
                best=choices
                if len(best)==1:break
        for i in best:
            visit(covered|cs[i][0],chosen+[i])
            if len(answers)>=limit:return
    visit(0,[])
    return answers

def partition(n,rng):
    pending=[(0,0,n,n)];rects=[]
    while pending:
        x,y,w,h=pending.pop()
        if w*h<=rng.randint(5,14) and w<=5 and h<=5:
            rects.append((x,y,w,h));continue
        if w>1 and (h==1 or rng.random()<w/(w+h)):
            cut=rng.randint(1,w-1);pending.extend([(x,y,cut,h),(x+cut,y,w-cut,h)])
        else:
            cut=rng.randint(1,h-1);pending.extend([(x,y,w,cut),(x,y+cut,w,h-cut)])
    return rects

def puzzle(n,seed):
    rng=random.Random(seed);rects=partition(n,rng)
    clues={}
    def place(r):
        x,y,w,h=r;p=(y+rng.randrange(h))*n+x+rng.randrange(w);clues[p]=w*h;return p
    tagged=[(*r,place(r)) for r in rects]
    for attempt in range(n*n):
        try:found=solutions(n,clues)
        except TimeoutError:found=[]
        if len(found)==1:return {'size':n,'seed':seed,'clues':sorted(clues.items()),'solution':tagged}
        # Refine a rectangle involved in ambiguity. Added clues restrict the
        # search, while the original tiling remains a known valid solution.
        same=set(found[0])&set(found[1]) if len(found)>1 else set()
        options=[r for r in tagged if r not in same and r[2]*r[3]>1]
        if not options:raise RuntimeError('cannot refine puzzle')
        r=max(options,key=lambda r:r[2]*r[3]);tagged.remove(r);x,y,w,h,p=r;del clues[p]
        if w>1 and (h==1 or w>=h):
            cut=rng.randint(1,w-1);parts=[(x,y,cut,h),(x+cut,y,w-cut,h)]
        else:
            cut=rng.randint(1,h-1);parts=[(x,y,w,cut),(x,y+cut,w,h-cut)]
        tagged.extend((*r,place(r)) for r in parts)
    raise RuntimeError('generation did not converge')

def render(puzzles):
    lines=['/* Generated by generate.py; original puzzles, unique by exact cover. */','const SPuzzle s_puzzles[S_PUZZLES] = {']
    for p in puzzles:
        # Six printable octets per solution rectangle: x,y,w,h,clue-x,clue-y.
        # Fixed +33 encoding avoids C octal escapes and C16 byte assumptions.
        data=''.join(chr(v+33) for x,y,w,h,at in p['solution'] for v in (x,y,w,h,at%p['size'],at//p['size']))
        data=data.replace('\\','\\\\').replace('"','\\"')
        lines.append(f'    {{{p["size"]}, {len(p["solution"])}, "{data}"}},')
    return '\n'.join(lines+['};',''])

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
    if a.check:
        puzzles=json.loads((ROOT/'puzzles.json').read_text())
        assert len(puzzles)==len(SIZES)*COUNT
        for p in puzzles:
            n=p['size'];clues=dict(p['clues']);found=solutions(n,clues)
            assert len(found)==1 and set(found[0])==set(map(tuple,p['solution']))
        assert (ROOT/'puzzles.inc').read_text()==render(puzzles)
        print(f'{len(puzzles)} puzzles: coverage, clues, unique solutions and generated C verified')
    else:
        puzzles=[]
        for n in SIZES:
            for i in range(COUNT):
                p=puzzle(n,0x53484900+n*COUNT+i);puzzles.append(p)
            print(f'{n}x{n}: {COUNT} unique puzzles',flush=True)
        (ROOT/'puzzles.json').write_text(json.dumps(puzzles,separators=(',',':'))+'\n')
        (ROOT/'puzzles.inc').write_text(render(puzzles))
if __name__=='__main__':main()
