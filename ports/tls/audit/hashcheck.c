/* Known-answer checks run with the guest C16 ABI on both code generators. */
#include <wolfssl/wolfcrypt/sha256.h>
#include <string.h>
#include <stdio.h>
static const byte abc_hash[32] = {
 0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
 0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad
};
static const byte empty_hash[32] = {
 0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
 0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55
};
static const byte million_hash[32] = {
 0xcd,0xc7,0x6e,0x5c,0x99,0x14,0xfb,0x92,0x81,0xa1,0xc7,0xe2,0x84,0xd7,0x3e,0x67,
 0xf1,0x80,0x9a,0x48,0xa4,0x97,0x20,0x0e,0x04,0x6d,0x39,0xcc,0xc7,0x11,0x2c,0xd0
};
int main(void) {
    wc_Sha256 s;
    byte output[34], data[1000];
    unsigned i;
    output[32] = 0x1234;
    output[33] = 0x5678;
    if (wc_InitSha256(&s) || wc_Sha256Final(&s,output) || memcmp(output,empty_hash,32)) return 1;
    if (wc_Sha256Update(&s,(const byte *)"a",1) || wc_Sha256Update(&s,(const byte *)"bc",2) ||
        wc_Sha256Final(&s,output) || memcmp(output,abc_hash,32)) return 2;
    memset(data,'a',1000);
    for (i=0;i<1000;i++) if (wc_Sha256Update(&s,data,1000)) return 3;
    if (wc_Sha256Final(&s,output) || memcmp(output,million_hash,32)) return 4;
    if (output[32]!=0x1234 || output[33]!=0x5678) return 5;
    for(i=0;i<32;i++) if(output[i]>255) return 6;
    wc_Sha256Free(&s);
    puts("SHA256 known answers passed");
    return 0;
}
