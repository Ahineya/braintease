static const byte signature[64]={0xe5,0x56,0x43,0x00,0xc3,0x60,0xac,0x72,0x90,0x86,0xe2,0xcc,0x80,0x6e,0x82,0x8a,0x84,0x87,0x7f,0x1e,0xb8,0xe5,0xd9,0x74,0xd8,0x73,0xe0,0x65,0x22,0x49,0x01,0x55,0x5f,0xb8,0x82,0x15,0x90,0xa3,0x3b,0xac,0xc6,0x1e,0x39,0x70,0x1c,0xf9,0xb4,0x6b,0xd2,0x5b,0xf5,0xf0,0x59,0x5b,0xbe,0x24,0x65,0x51,0x41,0x43,0x8e,0x7a,0x10,0x0b};
int main(void) {
    ed25519_key key;byte pub[32],sig[64],der[128];word32 n=64,at=0;int r,valid=0,failed=0;
#define CHECK(x) do {if(!(x)){fprintf(stderr,"crypto check failed at %d\n",__LINE__);failed=1;}}while(0)
    CHECK(ctMaskSelInt(255,83,-131)==83);CHECK(ctMaskSelInt(0,83,-131)==-131);
    CHECK(ctMaskSelInt(255,-32767,32767)==-32767);CHECK(ctMaskSelInt(0,-32767,32767)==32767);
    CHECK(ctMaskSelWord32(255,0x12345678UL,0xabcdef01UL)==0x12345678UL);
    CHECK(ctMaskSelWord32(0,0x12345678UL,0xabcdef01UL)==0xabcdef01UL);
    CHECK(wc_ed25519_init(&key)==0);CHECK(wc_ed25519_import_private_only(seed,32,&key)==0);
    CHECK(wc_ed25519_make_public(&key,pub,32)==0);CHECK(!memcmp(pub,public,32));
    CHECK(wc_ed25519_sign_msg((const byte *)"",0,sig,&n,&key)==0&&n==64);CHECK(!memcmp(sig,signature,64));
    CHECK(wc_ed25519_verify_msg(sig,64,(const byte *)"",0,&valid,&key)==0&&valid==1);
    sig[0]^=1;valid=1;r=wc_ed25519_verify_msg(sig,64,(const byte *)"",0,&valid,&key);CHECK(r<0||!valid);
    r=wc_Ed25519PrivateKeyToDer(&key,der,sizeof(der));CHECK(r>0);wc_ed25519_free(&key);
    CHECK(wc_ed25519_init(&key)==0);CHECK(wc_Ed25519PrivateKeyDecode(der,&at,&key,r)==0&&at==(word32)r);
    CHECK(wc_ed25519_make_public(&key,pub,32)==0);CHECK(!memcmp(pub,public,32));wc_ed25519_free(&key);
    puts(failed?"CRYPTO_FAILED":"CRYPTO_OK");return failed;
}
