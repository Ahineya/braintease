"""Explicit root identities and disposable GPT-backed root fixtures.

No physical provisioning: creation is exclusive and accepts a new regular file
only. The fixture's EFI/Ubuntu partitions are canaries, not real filesystems.
"""
import hashlib
import json
from pathlib import Path
import stat
import struct
import uuid
import zlib
from gpt_image import fixture, write_image, ESP, LINUX

ROOT_TYPE = uuid.UUID('a90c10b4-cb9d-4a61-8b6a-e8f4d16938cf')


def identity(sector=512, root_bytes=16 * 1024 * 1024):
    return dict(version=1, disk_guid='12345678-1234-5678-9abc-123456789abc',
                partition_guid='5946f329-8d99-4333-b387-04ea4fb7094b',
                first_lba=4 * 1024 * 1024 // sector,
                last_lba=(4 * 1024 * 1024 + root_bytes) // sector - 1, sector_bytes=sector)


def validate_identity(data):
    expected = {'version', 'disk_guid', 'partition_guid', 'first_lba', 'last_lba', 'sector_bytes'}
    if not isinstance(data, dict) or set(data) != expected or type(data['version']) is not int or data['version'] != 1:
        raise RuntimeError('root identity needs exactly the version-1 schema fields')
    for field in ('disk_guid', 'partition_guid'):
        try:
            value = uuid.UUID(data[field])
        except (ValueError, AttributeError, TypeError):
            raise RuntimeError(f'invalid {field}') from None
        if not value.int or str(value) != data[field]:
            raise RuntimeError(f'{field} must be a nonzero canonical UUID')
    first, last, sector = (data[k] for k in ('first_lba', 'last_lba', 'sector_bytes'))
    if any(type(x) is not int for x in (first, last, sector)) or sector not in (512, 1024, 2048, 4096):
        raise RuntimeError('invalid root identity LBA/sector fields')
    if not 34 <= first <= last < (1 << 64) // sector - 1 or first * sector % 2048 or \
            (last - first + 1) * sector < 16384 or (last - first + 1) * sector % 2048:
        raise RuntimeError('root identity has invalid native partition bounds')
    return data


def load_identity(path):
    return validate_identity(json.loads(Path(path).read_text()))


def header(data):
    validate_identity(data)
    def array(key):
        return '{' + ','.join(str(x) for x in uuid.UUID(data[key]).bytes_le) + '}'
    return ('/* Exact storage identity; generated by boot.py. */\n'
            'static const RootIdentity root_identity = {\n'
            f' .disk={array("disk_guid")}, .partition={array("partition_guid")},\n'
            f' .first={data["first_lba"]}ULL, .last={data["last_lba"]}ULL, .sector={data["sector_bytes"]}\n'
            '};\n')


def create_fixture(path, seed, data):
    """Seed only a new disposable virtual disk, with other partitions intact."""
    validate_identity(data)
    seed = Path(seed)
    info = seed.lstat()
    if not stat.S_ISREG(info.st_mode) or not 16384 <= info.st_size < 0x80000000 or info.st_size % 2048:
        raise RuntimeError('fixture seed must be a bounded regular C16 image')
    with seed.open('rb') as source:
        signature = source.read(19)
    sector = data['sector_bytes']
    reserved = (data['last_lba'] - data['first_lba'] + 1) * sector
    if info.st_size > reserved or signature != b'RIPPLE-FUZIX-C16-V3':
        raise RuntimeError('fixture partition must fit the C16 root seed')
    # A large reservation stays sparse; only the small seed is materialized.
    if data['first_lba'] * sector != 4 * 1024 * 1024 :
        raise RuntimeError('unsupported disposable fixture size/start')
    total = 8 * 1024 * 1024 + reserved
    image = fixture(sector, total // sector)
    entries = bytearray(16384)
    for i, (kind, guid, first, last, name) in enumerate([
            (ESP, uuid.UUID(int=100), 1024 * 1024 // sector, 2 * 1024 * 1024 // sector - 1, 'EFI canary'),
            (LINUX, uuid.UUID(int=101), 2 * 1024 * 1024 // sector, 4 * 1024 * 1024 // sector - 1, 'Ubuntu canary'),
            (ROOT_TYPE.bytes_le, uuid.UUID(data['partition_guid']), data['first_lba'], data['last_lba'], 'Riplix root')]):
        struct.pack_into('<16s16sQQQ72s', entries, i * 128, kind, guid.bytes_le, first, last, 0, name.encode('utf-16le'))
    for at, raw in list(image['spans'].items()):
        if len(raw) == 16384:
            image['spans'][at] = bytearray(entries)
        elif raw[:8] == b'EFI PART':
            raw[56:72] = uuid.UUID(data['disk_guid']).bytes_le
            struct.pack_into('<I', raw, 88, zlib.crc32(entries))
            struct.pack_into('<I', raw, 16, 0)
            struct.pack_into('<I', raw, 16, zlib.crc32(raw[:92]))
    start = data['first_lba'] * sector
    # Include the immediate neighbours of the write window and occupied areas.
    for at in (1024 * 1024, 2 * 1024 * 1024, start - 4096, start + info.st_size, start + reserved):
        image['spans'][at] = bytes((i * 17 + at // 4096) % 251 for i in range(4096))
    write_image(path, image)
    # Bounded sparse copy, never materialize a GiB seed in host RAM.
    with seed.open('rb') as source, Path(path).open('r+b') as target:
        at = start
        while True:
            chunk = source.read(1024 * 1024)
            if not chunk: break
            if any(chunk):
                target.seek(at); target.write(chunk)
            at += len(chunk)


def validate_disk(path, sector):
    info = Path(path).lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_size % sector or info.st_size < sector * 68:
        raise RuntimeError(f'partition disk must be a regular aligned image, never a device or symlink: {path}')


def outside_fingerprint(path, data):
    """Hash EVERY byte outside the partition, including on sparse large disks."""
    validate_disk(path, data['sector_bytes'])
    size = Path(path).stat().st_size
    first = data['first_lba'] * data['sector_bytes']
    end = (data['last_lba'] + 1) * data['sector_bytes']
    if end > size:
        raise RuntimeError('partition exceeds virtual disk')
    if size - (end - first) > 128 * 1024 * 1024:
        raise RuntimeError('outside-partition full hashing is limited to 128 MiB of test canaries')
    digest = hashlib.sha256()
    with Path(path).open('rb') as source:
        for start, length in ((0, first), (end, size - end)):
            source.seek(start)
            while length:
                raw = source.read(min(length, 1024 * 1024))
                if not raw:
                    raise RuntimeError('short virtual disk read')
                digest.update(raw); length -= len(raw)
    return dict(bytes=size - (end - first), sha256=digest.hexdigest(), coverage='all-bytes-outside-partition')


def damage_fixture(path, identity, case):
    """Test-only corruption of a disposable copy; preserve valid GPT CRCs where
    testing identity policy rather than the already-covered CRC rejection."""
    validate_disk(path, identity['sector_bytes'])
    if Path(path).stat().st_size > 128 * 1024 * 1024:
        raise RuntimeError('test mutation requires a small disposable virtual disk')
    raw = bytearray(Path(path).read_bytes())
    sector = identity['sector_bytes']
    if case == 'root-format':
        raw[identity['first_lba'] * sector] ^= 1
    elif case == 'root-size':
        struct.pack_into('<I', raw, identity['first_lba'] * sector + 2052, 0xffffffff)
    elif case == 'gpt-crc':
        raw[sector + 16] ^= 1
    else:
        for at in (sector, len(raw) - sector):
            array = struct.unpack_from('<Q', raw, at + 72)[0] * sector
            part = array + 2 * 128
            if case == 'wrong-disk': raw[at + 56] ^= 1
            elif case == 'wrong-partition': raw[part + 16] ^= 1
            elif case == 'wrong-type': raw[part:part + 16] = LINUX
            elif case == 'partition-readonly': struct.pack_into('<Q', raw, part + 48, 1 << 60)
            elif case == 'partition-moved':
                struct.pack_into('<Q', raw, part + 32, identity['first_lba'] + 8)
            else: raise RuntimeError(f'unknown fixture mutation {case}')
            struct.pack_into('<I', raw, at + 88, zlib.crc32(raw[array:array + 16384]))
            struct.pack_into('<I', raw, at + 16, 0)
            struct.pack_into('<I', raw, at + 16, zlib.crc32(raw[at:at + 92]))
    Path(path).write_bytes(raw)
