#!/usr/bin/env python3
"""Reproduce C16 arithmetic types from the unmodified, pinned stb import."""
import hashlib,json,re
from pathlib import Path
HERE=Path(__file__).resolve().parent

def prepare():
    audit=json.loads((HERE/'vendor/stb_image.json').read_text())
    raw=(HERE/'vendor/stb_image.h').read_bytes()
    if hashlib.sha256(raw).hexdigest()!=audit['sha256']:raise ValueError('Changed stb_image import')
    text=raw.decode()
    # Replace C type tokens only. Strings, comments, short coefficients and
    # octet cells remain intact. stb's arithmetic requires 32-bit int on C16.
    token=re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\bsigned\s+int\b|\bunsigned\s+int\b|\bunsigned\b(?!\s+(?:char|short|long)\b)|\bint\b|\bINT_MAX\b',re.S)
    def wide(m):
        value=m.group()
        if value=='int' or re.fullmatch(r'signed\s+int',value):return 'int32_t'
        if value=='unsigned' or re.fullmatch(r'unsigned\s+int',value):return 'uint32_t'
        if value=='INT_MAX':return 'INT32_MAX'
        return value
    text=token.sub(wide,text)
    text=text.replace('sizeof(stbi__uint32)==4','sizeof(stbi__uint32)==sizeof(uint32_t)')
    # The upstream marker-error branch accepts a partial JPEG. Our API promises
    # transactional failure, not a partially decoded image presented as success.
    assert text.count('if (!stbi__process_marker(j, m)) return 1;')==1
    text=text.replace('if (!stbi__process_marker(j, m)) return 1;','if (!stbi__process_marker(j, m)) return 0;')
    # Explicitly widen octet shifts; C16's char promotions are only 16 bits.
    text=re.sub(r'\b1\s*<<', '(int32_t)1 <<', text)
    text=text.replace('(128<<17)', '((int32_t)128<<17)')
    text=text.replace('(y[i] << 20)', '((int32_t)y[i] << 20)')
    text=text.replace('pcr[i] - 128', '(int32_t)pcr[i] - 128')
    text=text.replace('pcb[i] - 128', '(int32_t)pcb[i] - 128')
    # Host UBSan mutation tests exercise coefficient patterns beyond ordinary
    # photographs. The scalar IDCT's second pass needs wider intermediates.
    text=text.replace('int32_t t0,t1,t2,t3,p1,p2,p3,p4,p5,x0,x1,x2,x3;',
                      'int64_t t0,t1,t2,t3,p1,p2,p3,p4,p5,x0,x1,x2,x3;')
    text=text.replace('stbi__clamp(int32_t x)', 'stbi__clamp(int64_t x)')
    text=text.replace('if ((uint32_t) x > 255)', 'if (x < 0 || x > 255)')
    path=HERE/'stb-codec.inc'
    text='/* Generated by adapt_stb.py: fixed-width C16 arithmetic, strict marker errors. */\n'+text
    if not path.exists() or path.read_text()!=text:path.write_text(text)
if __name__=='__main__':prepare()
