// Maintainer-only: bake pinned Graphite/Lucide artwork for the portable dock.
// Ordinary builds read the checked-in masks, without Node or an SVG renderer.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const require = createRequire(import.meta.url);
const sharp = require(process.env.LVGL_SHARP_MODULE || 'sharp');
const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../../ports/fusede/icons/lucide');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'UPSTREAM.json')));
const files = manifest.files.filter(f => f.file.endsWith('.svg')).sort((a,b) => a.file.localeCompare(b.file, 'en'));
const hashes = {};
for (const size of [32, 64]) {
    const masks = [];
    for (const file of files) {
        const input = fs.readFileSync(path.join(source, file.file));
        if (createHash('sha256').update(input).digest('hex') !== file.sha256)
            throw Error(`Changed pinned source: ${file.file}`);
        const svg = input.toString().replaceAll('currentColor', '#ffffff');
        const {data, info} = await sharp(Buffer.from(svg), {density:72*size/24*4})
            .resize(size,size).ensureAlpha().raw().toBuffer({resolveWithObject:true});
        if (info.width !== size || info.height !== size || info.channels !== 4)
            throw Error('Unexpected raster');
        masks.push(Buffer.from(Array.from({length:size*size}, (_,i) => data[i*4+3])));
    }
    const data = Buffer.concat(masks);
    const name = `lucide-${size}.bin`;
    fs.writeFileSync(path.join(here,name),data);
    hashes[name] = createHash('sha256').update(data).digest('hex');
}
const names = files.map(f => f.file.slice(0,-4));
fs.writeFileSync(path.join(here,'names.rs'), '// Generated by generate.mjs. Lucide artwork: ISC / Feather MIT.\n'+
    'const NAMES: &[&str] = &['+names.map(n => JSON.stringify(n)).join(',')+'];\n');
fs.copyFileSync(path.join(source,'LICENSE'),path.join(here,'LICENSE.Lucide.txt'));
fs.writeFileSync(path.join(here,'provenance.json'),JSON.stringify({
    revision:manifest.revision,source:'../../../ports/fusede/icons/lucide/UPSTREAM.json',
    logical_size:32,sizes:[32,64],names,
    rasterizer:{sharp:sharp.versions.sharp,vips:sharp.versions.vips,rsvg:sharp.versions.rsvg,supersampling:4},
    sha256:hashes
},null,2)+'\n');
