#!/usr/bin/env python3
"""Regenerate pinned Unicode 16 tables and a compact bitmap font subset."""
import gzip,hashlib,json
from pathlib import Path
from urllib.request import urlopen
ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
CACHE=ROOT/'build/unicode/vendor'
KINDS=['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']

def load(name):
    item=json.loads((HERE/'sources.json').read_text())[name]
    p=CACHE/name;p.parent.mkdir(parents=True,exist_ok=True)
    data=p.read_bytes() if p.exists() else urlopen(item['url'],timeout=60).read()
    if hashlib.sha256(data).hexdigest()!=item['sha256']:raise ValueError('Hash mismatch: '+name)
    p.write_bytes(data);return data

def ranges(text,selector):
    values=[]
    for line in text.splitlines():
        s=line.split('#')[0].strip()
        if not s:continue
        parts=[v.strip() for v in s.split(';')]
        value=selector(parts)
        if value is None:continue
        span=parts[0].split('..');values.append((int(span[0],16),int(span[-1],16),value))
    values.sort();merged=[]
    for lo,hi,v in values:
        if merged and merged[-1][1]+1==lo and merged[-1][2]==v:merged[-1]=(merged[-1][0],hi,v)
        else:merged.append((lo,hi,v))
    return merged

def main():
    tables={'gcb':ranges(load('GraphemeBreakProperty.txt').decode(),lambda p:None if p[1] in ('LV','LVT') else KINDS.index(p[1])),
            'wide':ranges(load('EastAsianWidth.txt').decode(),lambda p:1 if p[1] in ('W','F') else None),
            'pictographic':ranges(load('emoji-data.txt').decode(),lambda p:1 if p[1]=='Extended_Pictographic' else None),
            'incb':ranges(load('DerivedCoreProperties.txt').decode(),lambda p:{'Consonant':1,'Extend':2,'Linker':3}.get(p[2]) if len(p)>2 and p[1]=='InCB' else None)}
    out=['/* Generated by generate.py from pinned Unicode 16.0.0 data. */']
    for name,entries in tables.items():
        out.append('static const struct ru_range ru_'+name+'_table[] = {')
        out.extend('    {0x%xUL,0x%xUL,%d},'%(lo,hi,v) for lo,hi,v in entries)
        out.append('};')
    (HERE/'tables.inc').write_text('\n'.join(out)+'\n')
    # Latin, Greek, Cyrillic, marks, line graphics, punctuation and replacement.
    selected=[(0x20,0x7f),(0xa0,0x530),(0x1e00,0x2000),(0x2000,0x2070),(0x2190,0x2200),(0x2500,0x2600),(0xfffd,0xfffe)]
    glyphs=[]
    for line in gzip.decompress(load('unifont.hex.gz')).decode().splitlines():
        cp,data=line.split(':');cp=int(cp,16)
        if any(a<=cp<b for a,b in selected):
            raw=bytes.fromhex(data)
            rows=[raw[y]<<8 for y in range(16)] if len(raw)==16 else [raw[y*2]*256+raw[y*2+1] for y in range(16)]
            glyphs.append((cp,8 if len(raw)==16 else 16,rows))
    lines=['/* Ripple terminal bitmap subset, derived from GNU Unifont 16.0.04. */',
           '/* Font data: OFL-1.1; see FONT-COPYRIGHT.txt and FONT-LICENSE.txt. */',
           'static const uint16_t ru_font_codes[] = {']
    lines.extend('    '+','.join('0x%x'%g[0] for g in glyphs[i:i+16])+',' for i in range(0,len(glyphs),16));lines.append('};')
    lines.append('static const uint16_t ru_font_rows[][16] = {')
    lines.extend('    {'+','.join('0x%04x'%r for r in rows)+'},' for cp,width,rows in glyphs);lines.append('};')
    (HERE/'font.inc').write_text('\n'.join(lines)+'\n')
    (HERE/'UNICODE-LICENSE.txt').write_bytes(load('Unicode-LICENSE.txt'))
    (HERE/'FONT-LICENSE.txt').write_bytes(load('Unifont-OFL.txt'))
    print('generated',len(glyphs),'glyphs;',sum(map(len,tables.values())),'property ranges')
if __name__=='__main__':main()
